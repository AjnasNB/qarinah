import assert from "node:assert/strict";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const packageJson = JSON.parse(await readFile(path.join(repositoryRoot, "package.json"), "utf8"));
const pluginRoot = path.join(repositoryRoot, "integrations", "codex", "qarinah");
const pluginManifest = JSON.parse(await readFile(path.join(pluginRoot, ".codex-plugin", "plugin.json"), "utf8"));
assert.equal(pluginManifest.version, packageJson.version, "Plugin and package versions must match.");

const checking = process.argv.includes("--check");
const temporaryDirectory = checking ? await mkdtemp(path.join(os.tmpdir(), "qarinah-plugin-build-")) : null;
const outputFile = checking
  ? path.join(temporaryDirectory, "qarinah.mjs")
  : path.join(pluginRoot, "runtime", "qarinah.mjs");

try {
  const result = await build({
    entryPoints: [path.join(repositoryRoot, "bin", "qarinah.js")],
    outfile: outputFile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    sourcemap: false,
    minify: false,
    legalComments: "inline",
    metafile: true,
    banner: { js: `// GENERATED by scripts/build-codex-plugin.mjs for Qarinah ${packageJson.version}. DO NOT EDIT.` },
    logLevel: "silent"
  });
  const externalImports = Object.values(result.metafile.outputs)
    .flatMap((output) => output.imports)
    .filter((entry) => entry.external)
    .map((entry) => entry.path);
  const unsafeExternal = externalImports.filter((specifier) => !specifier.startsWith("node:"));
  assert.deepEqual(unsafeExternal, [], `Plugin bundle has non-Node external imports: ${unsafeExternal.join(", ")}`);

  const generated = await readFile(outputFile);
  assert.equal(generated.includes(Buffer.from(repositoryRoot)), false, "Plugin bundle contains an absolute repository path.");
  if (checking) {
    const committed = await readFile(path.join(pluginRoot, "runtime", "qarinah.mjs"));
    assert.deepEqual(generated, committed, "Committed Codex plugin runtime is stale. Run `npm run build:codex-plugin`.");
    process.stdout.write("Codex plugin runtime is current.\n");
  } else {
    process.stdout.write(`Built ${path.relative(repositoryRoot, outputFile)}\n`);
  }
} finally {
  if (temporaryDirectory) await rm(temporaryDirectory, { recursive: true, force: true });
}
